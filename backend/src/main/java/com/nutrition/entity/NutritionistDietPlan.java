package com.nutrition.entity;

import jakarta.persistence.*;
import lombok.Data;
import org.hibernate.annotations.CreationTimestamp;

import java.time.LocalDateTime;

/**
 * A diet plan published by a nutritionist.
 *
 * Kept separate from {@link DietPlan}, which holds a user's own personal/AI plans.
 * The author comes from the authenticated session, never from the request body, so
 * visibility, deletion and notification rules can be enforced on the server.
 *
 * GENERAL plans are visible to every client account; EXCLUSIVE plans only to
 * {@code targetUser} and the author. {@code payloadJson} preserves the exact plan
 * shape consumed by the existing card grid and import handler.
 */
@Entity
@Table(name = "nutritionist_diet_plans")
@Data
public class NutritionistDietPlan {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** Stable id generated by the builder; used by the frontend for deploy/delete. */
    @Column(name = "plan_key", nullable = false, length = 120)
    private String planKey;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "nutritionist_id", nullable = false)
    private User nutritionist;

    /** GENERAL or EXCLUSIVE. */
    @Column(nullable = false, length = 16)
    private String scope;

    /** Required for EXCLUSIVE plans, null for GENERAL plans. */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "target_user_id")
    private User targetUser;

    @Column(nullable = false)
    private String title;

    @Column(name = "payload_json", nullable = false, columnDefinition = "LONGTEXT")
    private String payloadJson;

    /** Soft delete keeps imported targets and tracking history untouched. */
    @Column(nullable = false)
    private boolean deleted = false;

    @CreationTimestamp
    @Column(name = "created_at", updatable = false)
    private LocalDateTime createdAt;
}
